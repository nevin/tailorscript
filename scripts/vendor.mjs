// Rebuilds src/vendor/codemirror/ from the CodeMirror packages in devDependencies.
// The bundle is committed, so the extension still loads from src/ without a build step.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { build } from "esbuild";
import { readJson, relative, root } from "./lib/project.mjs";

const outDir = path.join(root, "src/vendor/codemirror");
const result = await build({
  entryPoints: [path.join(root, "scripts/vendor/codemirror-entry.mjs")],
  bundle: true,
  format: "esm",
  minify: true,
  target: "chrome138",
  legalComments: "none",
  metafile: true,
  write: false
});

// Credit every package that ended up in the bundle.
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
  if (match && !packages.has(match[1])) {
    const dir = path.join(root, "node_modules", match[1]);
    const { version, license } = await readJson(path.join(dir, "package.json"));
    const text = await readFile(path.join(dir, "LICENSE"), "utf8").catch(() => `${license} license`);
    packages.set(match[1], { version, text });
  }
}
const names = [...packages.keys()].sort();
const banner = `// CodeMirror 6 bundle for Tailorscript. Generated by scripts/vendor.mjs; do not edit.\n// ${names.map(name => `${name}@${packages.get(name).version}`).join(", ")}\n`;
await mkdir(outDir, { recursive: true });
await writeFile(path.join(outDir, "codemirror.js"), banner + result.outputFiles[0].text);
await writeFile(path.join(outDir, "LICENSE"), names.map(name => `${name} ${packages.get(name).version}\n\n${packages.get(name).text.trim()}\n`).join("\n---\n\n"));
const size = Buffer.byteLength(result.outputFiles[0].text);
console.log(`\u001b[32m✔\u001b[0m Bundled ${names.length} packages into ${relative(outDir)}/codemirror.js (${(size / 1024).toFixed(1)} KB)`);
