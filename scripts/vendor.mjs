// Rebuilds src/vendor/codemirror/ from the CodeMirror packages in devDependencies.
// The bundle is committed, so the extension still loads from src/ without a build step.
// With --check it writes nothing and fails if the committed files differ from a fresh build (run in CI).
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { build } from "esbuild";
import { readJson, relative, root } from "./lib/project.mjs";

const outDir = path.join(root, "src/vendor/codemirror");
const result = await build({
  entryPoints: [path.join(root, "scripts/vendor/codemirror-entry.mjs")],
  bundle: true,
  format: "esm",
  minify: true,
  target: "chrome138",
  legalComments: "none",
  metafile: true,
  write: false
});

// Credit every package that ended up in the bundle.
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
  if (match && !packages.has(match[1])) {
    const dir = path.join(root, "node_modules", match[1]);
    const { version, license } = await readJson(path.join(dir, "package.json"));
    const text = await readFile(path.join(dir, "LICENSE"), "utf8").catch(() => `${license} license`);
    packages.set(match[1], { version, text });
  }
}
const names = [...packages.keys()].sort();
const banner = `// CodeMirror 6 bundle for Tailorscript. Generated by scripts/vendor.mjs; do not edit.\n// ${names.map(name => `${name}@${packages.get(name).version}`).join(", ")}\n`;
// Type declarations re-export the packages' own types, so tsc can check code that imports the bundle.
const entry = await readFile(path.join(root, "scripts/vendor/codemirror-entry.mjs"), "utf8");
const outputs = {
  "codemirror.js": banner + result.outputFiles[0].text,
  "codemirror.d.ts": "// Types for the CodeMirror bundle, taken from the npm packages. Generated by scripts/vendor.mjs; not shipped.\n" +
    entry.slice(entry.indexOf("\n") + 1),
  LICENSE: names.map(name => `${name} ${packages.get(name).version}\n\n${packages.get(name).text.trim()}\n`).join("\n---\n\n")
};

if (process.argv.includes("--check")) {
  const stale = [];
  for (const [name, text] of Object.entries(outputs)) {
    if (await readFile(path.join(outDir, name), "utf8").catch(() => null) !== text) stale.push(name);
  }
  if (stale.length) {
    console.error(`\u001b[31m✖\u001b[0m ${relative(outDir)}/ doesn’t match a fresh build of package-lock.json: ${stale.join(", ")}. Run npm run vendor and commit the result.`);
    process.exit(1);
  }
  console.log(`\u001b[32m✔\u001b[0m ${relative(outDir)}/ matches a fresh build of ${names.length} packages.`);
  process.exit(0);
}

await mkdir(outDir, { recursive: true });
for (const [name, text] of Object.entries(outputs)) await writeFile(path.join(outDir, name), text);
const size = Buffer.byteLength(result.outputFiles[0].text);
console.log(`\u001b[32m✔\u001b[0m Bundled ${names.length} packages into ${relative(outDir)}/codemirror.js (${(size / 1024).toFixed(1)} KB)`);
